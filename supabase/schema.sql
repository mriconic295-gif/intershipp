-- Only the KAVACH host/admin account should be listed here.
create table if not exists public.admin_owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_owners enable row level security;

drop policy if exists "owners can read own owner record" on public.admin_owners;
create policy "owners can read own owner record" on public.admin_owners
for select to authenticated using (user_id = auth.uid());

create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  organization text,
  phone text not null,
  email text not null,
  service text not null,
  message text not null
);

alter table public.inquiries enable row level security;

drop policy if exists "public can submit inquiries" on public.inquiries;
create policy "public can submit inquiries" on public.inquiries
for insert to anon, authenticated with check (true);

drop policy if exists "admins can read inquiries" on public.inquiries;
create policy "admins can read inquiries" on public.inquiries
for select to authenticated using (exists (select 1 from public.admin_owners where user_id = auth.uid()));

alter table public.inquiries add column if not exists status text not null default 'Received';

drop policy if exists "authenticated can update inquiries" on public.inquiries;
create policy "authenticated can update inquiries" on public.inquiries
for update to authenticated
using (exists (select 1 from public.admin_owners where user_id = auth.uid()))
with check (exists (select 1 from public.admin_owners where user_id = auth.uid()));

-- Login activity for customer and admin accounts. Browser-safe details only;
-- no password, token or secret is stored.
create table if not exists public.login_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text,
  login_type text not null default 'customer',
  logged_at timestamptz not null default now(),
  user_agent text,
  platform text,
  screen_width integer,
  screen_height integer,
  language text,
  timezone text,
  referrer text
);

alter table public.login_logs enable row level security;

drop policy if exists "users can insert own login logs" on public.login_logs;
create policy "users can insert own login logs" on public.login_logs
for insert to authenticated
with check (user_id = auth.uid());

drop policy if exists "owners can read login logs" on public.login_logs;
create policy "owners can read login logs" on public.login_logs
for select to authenticated
using (exists (select 1 from public.admin_owners where user_id = auth.uid()));
